package emit

// ---------------------------------------------------------------------------
// F5：循环体内容器访问的**缓存形态**（§10.4 第 2 条的无证明健全版）。
//
// 适用条件（都可机械检查）：容器是**本函数的局部切片变量**（裸名）、循环体内**句柄不变**
// （不被整体重新赋值）、且体内按下标访问它。缓存 len/data 后热路径只比较 + 读写；慢路径
// （越界/增长）走原访问器并刷新缓存 ⇒ 语义完全不变（越界写仍增长 + 补零、越界读仍 trap）。
// ---------------------------------------------------------------------------

// endCache：循环结束后撤销缓存登记（避免泄漏到循环外的访问点）。
func (c *Ctx) endCache() {
	c.cached = nil
	c.cachedCT = nil
}
